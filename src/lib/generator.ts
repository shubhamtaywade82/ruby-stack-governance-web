// Deterministic generators: turn a BuilderConfig into the exact files a repo needs.
// Used server-side by POST /api/generate.

import type { BuilderConfig } from "./rubocop";
import { EXCLUDE_OPTIONS, PLUGIN_ORDER, presetLabel } from "./rubocop";

export interface GeneratedFiles {
  rubocopYml: string;
  gemfile: string;
  ciWorkflow: string;
  lintScript: string;
  setup: string;
}

const OPTIONAL_PLUGINS = [
  "rubocop-graphql",
  "rubocop-thread_safety",
  "rubocop-yard",
  "rubocop-minitest",
  "rubocop-rails-omakase",
];

function padComment(text: string, comment?: string, column = 44): string {
  if (!comment) return text;
  const pad = text.length >= column ? "  " : " ".repeat(column - text.length);
  return `${text}${pad}# ${comment}`;
}

export function generateAll(config: BuilderConfig): GeneratedFiles {
  return {
    rubocopYml: generateRubocopYml(config),
    gemfile: generateGemfile(config),
    ciWorkflow: generateCiWorkflow(config),
    lintScript: generateLintScript(),
    setup: generateSetup(config),
  };
}

function generateRubocopYml(c: BuilderConfig): string {
  const has = (key: string) => c.plugins.includes(key);
  const rails = has("rubocop-rails");
  const rspec = has("rubocop-rspec");
  const plugins = PLUGIN_ORDER.filter((p) => c.plugins.includes(p));
  const m = c.metrics;
  const t = c.toggles;
  const L: string[] = [];
  const w = (s = "") => L.push(s);
  const kv = (key: string, value: string | number, comment?: string) =>
    w(comment ? padComment(`  ${key}: ${value}`, comment, 44) : `  ${key}: ${value}`);

  // ── Header ─────────────────────────────────────────────────────────────────
  w("# ===========================================================================");
  w("# .rubocop.yml — organization-wide RuboCop enforcement baseline");
  w("# ===========================================================================");
  w("# Generated by Stack Governance Studio");
  w(`# Preset: ${presetLabel(c.preset)} · Target: Ruby ${c.rubyVersion}${rails ? ` / Rails ${c.railsVersion}` : ""}`);
  w("#");
  w("# Style sources:");
  w("#   Ruby Style Guide   — https://rubystyle.guide");
  w("#   Rails Style Guide  — https://github.com/rubocop/rails-style-guide");
  w("#   RSpec Style Guide  — https://github.com/rubocop/rspec-style-guide");
  w("#   Plugins            — https://docs.rubocop.org/rubocop/latest/plugins.html");
  w("#");
  w("# Deterministic governance: commit this file at the repo root. It is the");
  w("# single source of truth — the CI gate fails on any deviation.");
  w("# ===========================================================================");
  w("");

  if (c.legacyTodo) {
    w("# Legacy adoption: existing violations are frozen in .rubocop_todo.yml.");
    w("# Strict rules apply to NEW code; refactor files out of the todo as you");
    w("# touch them (the Boy Scout rule).");
    w("inherit_from: .rubocop_todo.yml");
    w("");
  }

  if (plugins.length > 0) {
    w("# --- Plugins (modern `plugins:` directive, RuboCop >= 1.72) -----------------");
    w("plugins:");
    plugins.forEach((p) => w(`  - ${p}`));
    w("");
  }

  // ── 1 · Global settings ─────────────────────────────────────────────────────
  w("# --- 1 · Global settings ----------------------------------------------------");
  w("AllCops:");
  kv("TargetRubyVersion", c.rubyVersion);
  if (rails) kv("TargetRailsVersion", c.railsVersion, "rubocop-rails");
  kv("NewCops", c.newCops ? "enable" : "disable", "adopt cops introduced in minor upgrades");
  kv("SuggestExtensions", c.suggestExtensions ? "true" : "false", "keep CI output quiet");
  w("  Exclude:");
  for (const pattern of c.excludes) {
    const note = EXCLUDE_OPTIONS.find((o) => o.pattern === pattern)?.note;
    w(padComment(`    - '${pattern}'`, note ?? "", 44));
  }
  w("");

  // ── 2 · Layout ──────────────────────────────────────────────────────────────
  w("# --- 2 · Layout — formatting ------------------------------------------------");
  w('# Corpus: "line (less than 100 columns)" · "vertical alignment (left)" ·');
  w('# "leave space around the operators" · "avoid too many new lines"');
  w("Layout/LineLength:");
  kv("Max", m.lineLength, "corpus: <= 100 columns");
  kv("AllowedPatterns", "['\\A#']", "long YARD / W5H comments stay legal");
  w("  Exclude:");
  w("    - 'config/**/*'");
  w("");
  w("Layout/MultilineMethodCallIndentation:");
  kv("EnforcedStyle", "aligned", "wrap lengthy lines, aligned left");
  w("");
  w("Layout/SpaceAroundOperators:");
  kv("Enabled", "true", "leave space around the operators");
  w("");
  w("Layout/EmptyLinesAroundClassBody:");
  kv("EnforcedStyle", "empty_lines_except_namespace", "avoid too many new lines");
  w("");

  // ── 3 · Metrics ─────────────────────────────────────────────────────────────
  w("# --- 3 · Metrics — size & complexity ----------------------------------------");
  w('# Corpus: "methods < 10 lines" · "classes < 250 LOC" · "max 2 arguments".');
  w("# Tests carry their own budgets (RSpec/ExampleLength) — keep them out of here.");
  w("Metrics/MethodLength:");
  kv("Max", m.methodLength, "corpus: methods < 10 lines");
  w("  Exclude:");
  w("    - 'db/seeds.rb'");
  w(padComment("    - 'spec/**/*'", "RSpec cops govern spec files", 44));
  w("");
  w("Metrics/ClassLength:");
  kv("Max", m.classLength, "corpus: classes < 250 LOC");
  if (c.preset !== "maximum") {
    w("  Exclude:");
    w(padComment("    - 'app/controllers/**/*'", "controllers run long in complex apps", 44));
  }
  w("");
  w("Metrics/ModuleLength:");
  kv("Max", m.moduleLength);
  w("");
  w("Metrics/BlockLength:");
  w("  Exclude:");
  w("    - 'spec/**/*'");
  w("    - 'config/routes.rb'");
  w("    - 'config/environments/**/*'");
  w("    - 'lib/tasks/**/*'");
  w("");
  w("Metrics/AbcSize:");
  kv("Max", m.abcSize);
  w("");
  w("Metrics/CyclomaticComplexity:");
  kv("Max", m.cyclomatic);
  w("");
  w("Metrics/ParameterLists:");
  kv("Max", m.parameterLists, "corpus: max 2 arguments");
  kv("CountKeywordArgs", "false", "kwargs beyond 2 positional args are fine");
  w("");

  // ── 4 · Style ───────────────────────────────────────────────────────────────
  w("# --- 4 · Style — idiomatic Ruby ---------------------------------------------");
  if (t.singleQuotes) {
    w("Style/StringLiterals:");
    kv("EnforcedStyle", "single_quotes");
    w("");
  }
  w("Style/Documentation:");
  kv("Enabled", t.documentation ? "true" : "false", t.documentation ? "corpus mandates YARD (W5H) docs" : "intent-revealing names + PR checklist instead");
  w("");
  w("Style/FrozenStringLiteralComment:");
  kv("Enabled", t.frozenStringLiteral ? "true" : "false", t.frozenStringLiteral ? "magic comment on every file" : "noise in modern Ruby");
  w("");
  if (t.strictRescue) {
    w("Style/RescueStandardError:");
    kv("EnforcedStyle", "explicit", "be specific about what you rescue");
    w("");
  }
  w("Style/RedundantReturn:");
  kv("Enabled", "true", "no explicit return on the last line");
  w("");
  w("Style/CaseLikeIf:");
  kv("Enabled", "true", "case/when over lengthy if chains");
  w("");
  w("Style/For:");
  kv("Enabled", "true", "each with a block over for loops");
  w("");
  w("Style/NegatedIf:");
  kv("Enabled", "true", "unless over negative conditions");
  w("");
  w("Style/Not:");
  kv("Enabled", "true", "no !(…) in conditions");
  w("");
  w("Style/ClassVars:");
  kv("Enabled", "true", "@@ must be strategic");
  w("");
  w("Style/GlobalVars:");
  kv("Enabled", "true", "no globals / monkey-patch side effects");
  w("");
  w("Style/TrivialAccessors:");
  kv("Enabled", "true");
  kv("ExactNameMatch", "true");
  kv("AllowPredicates", "true", "attr_* where appropriate");
  w("");
  w("Style/RescueModifier:");
  kv("Enabled", "true", "never `do_something rescue nil`");
  w("");

  // ── 5 · Naming ──────────────────────────────────────────────────────────────
  w("# --- 5 · Naming — semantics at a glance -------------------------------------");
  w("# Corpus: classes are nouns, methods are verbs, booleans take the ? suffix,");
  w("# file names match the classes they define. Semantic quality (no `temp`,");
  w("# `arr`, `data`) still requires human review — see the PR checklist.");
  for (const cop of ["ClassName", "MethodName", "PredicateName", "FileName", "VariableName"]) {
    w(`Naming/${cop}:`);
    kv("Enabled", "true");
    w("");
  }

  // ── 6 · Rails ───────────────────────────────────────────────────────────────
  if (rails) {
    w("# --- 6 · Rails — framework boundaries ----------------------------------------");
    if (t.filePathArguments) {
      w("Rails/FilePath:");
      kv("EnforcedStyle", "arguments", "Rails.root.join('app', 'models') — no interpolation");
      w("");
    }
    w("Rails/UnknownEnv:");
    w("  Environments:");
    w("    - production");
    w("    - development");
    w("    - test");
    w(padComment("    - staging", "add custom environments here", 44));
    w("");
    w("Rails/ReversibleMigration:");
    kv("Enabled", "true", "enforce safe migrations");
    w("");
    if (t.i18nTexts) {
      w("Rails/I18nLocaleTexts:");
      kv("Enabled", "true", "static text belongs in en.yml");
      w("");
    }
    w("Rails/Validation:");
    kv("Enabled", "true", "DRY validations (presence: true once)");
    w("");
    w("Rails/FindBy:");
    kv("Enabled", "true", "find_by over where.first");
    w("");
    w("Rails/ReadWriteAttribute:");
    kv("Enabled", "true", "self[:attr] over read_attribute");
    w("");
    w("Rails/HasManyOrHasOneDependent:");
    kv("Enabled", "true", "declare dependent: explicitly");
    w("");
    w("Rails/HelperInstanceVariable:");
    kv("Enabled", "true", "helpers take arguments, not ivars");
    w("");
    w("Rails/RenderInline:");
    kv("Enabled", "true", "partials over inline strings");
    w("");
  }

  // ── 7 · RSpec ───────────────────────────────────────────────────────────────
  if (rspec) {
    w("# --- 7 · RSpec — BetterSpecs structure ----------------------------------------");
    w("# BetterSpecs: one behavior per example, contexts describe a state, verified");
    w("# doubles only, expect(actual).to eq(expected).");
    if (t.contextWording) {
      w("RSpec/ContextWording:");
      w("  Prefixes:");
      w("    - when");
      w("    - with");
      w("    - without");
      w("    - if");
      w("    - unless");
      w("    - for");
      w("");
    }
    w("RSpec/MultipleExpectations:");
    kv("Max", m.rspecExpectations, "BetterSpecs: single expectation");
    w("");
    w("RSpec/ExampleLength:");
    kv("Max", m.rspecExampleLength, "keep the it block short");
    w("");
    w("RSpec/MultipleMemoizedHelpers:");
    kv("Max", m.rspecMemoized);
    w("");
    w("RSpec/NestedGroups:");
    kv("Max", m.rspecNested);
    w("");
    if (t.verifiedDoubles) {
      w("RSpec/VerifiedDoubles:");
      kv("EnforcedStyle", "verified", "instance_double over double");
      w("");
    }
    if (t.messageSpies) {
      w("RSpec/MessageSpies:");
      kv("EnforcedStyle", "have_received", "allow first, assert after");
      w("");
    }
    w("RSpec/NamedSubject:");
    kv("Enabled", "true");
    w("");
    w("RSpec/DescribedClass:");
    kv("Enabled", "true");
    w("");
    w("RSpec/DescribeClass:");
    kv("Enabled", "true");
    w("  Exclude:");
    w(padComment("    - 'spec/features/**/*'", "system specs describe a flow, not a class", 44));
    w("    - 'spec/requests/**/*'");
    w("");
    w("RSpec/SubjectStub:");
    kv("Enabled", "true", "never stub the object under test");
    w("");
    w("RSpec/InstanceVariable:");
    kv("Enabled", "true", "let over @ivars in specs");
    w("");
    w("RSpec/BeforeAfterAll:");
    kv("Enabled", "true", "before(:all) leaks state");
    w("");
  }

  // ── 8 · RSpecRails ──────────────────────────────────────────────────────────
  if (has("rubocop-rspec_rails")) {
    w("# --- 8 · RSpecRails ------------------------------------------------------------");
    w("RSpecRails/HaveHttpStatus:");
    kv("Enabled", "true", "request specs: expect(response).to have_http_status");
    w("");
    w("RSpecRails/InferredSpecType:");
    kv("Enabled", "true", "don't repeat `type: :request`");
    w("");
  }

  // ── 9 · FactoryBot ──────────────────────────────────────────────────────────
  if (has("rubocop-factory_bot")) {
    w("# --- 9 · FactoryBot --------------------------------------------------------------");
    w("FactoryBot/AttributeDefinedStatically:");
    kv("Enabled", "true", "dynamic attributes belong in blocks");
    w("");
    w("FactoryBot/CreateList:");
    kv("Enabled", "true", "create_list over loops");
    w("");
    w("FactoryBot/SyntaxMethods:");
    kv("Enabled", "true", "create_list(:user) over FactoryBot.create_list");
    w("");
  }

  // ── 10 · Capybara ───────────────────────────────────────────────────────────
  if (has("rubocop-capybara")) {
    w("# --- 10 · Capybara -----------------------------------------------------------------");
    w("Capybara/CurrentPathExpectation:");
    kv("Enabled", "true", "have_current_path matcher over assertions");
    w("");
    w("Capybara/SpecificMatcher:");
    kv("Enabled", "true", "find_button over find('.btn')");
    w("");
  }

  // ── 11 · Rake ───────────────────────────────────────────────────────────────
  if (has("rubocop-rake")) {
    w("# --- 11 · Rake -----------------------------------------------------------------------");
    w("Rake/Desc:");
    kv("Enabled", "true", "every task gets a desc");
    w("");
  }

  // ── 12 · Performance ────────────────────────────────────────────────────────
  if (has("rubocop-performance")) {
    w("# --- 12 · Performance -----------------------------------------------------------------");
    w("# rubocop-performance runs at defaults: reverse_each, size over count, flat_map,");
    w("# sum over inject(:+), double_negation, string replacement, constant regexps.");
    w("");
  }

  const optionalSelected = OPTIONAL_PLUGINS.filter((p) => has(p));
  if (optionalSelected.length > 0) {
    w(`# --- Optional plugins loaded: ${optionalSelected.join(", ")}`);
    w("# These run at their defaults; tune here if the stack demands it.");
    w("");
  }

  w("# ===========================================================================");
  w("# Beyond static analysis — enforce in PR reviews:");
  w("#   • Intention-revealing names — no `temp`, `arr`, `data`, `pro`");
  w("#   • Business logic in models/services — controllers stay HTTP-thin");
  w("#   • Never use exceptions for control flow — find_by / exists? instead");
  w("#   • W5H (What·Why·When·Where·Who·How) on complex classes");
  w("# ===========================================================================");
  return L.join("\n") + "\n";
}

function generateGemfile(c: BuilderConfig): string {
  const has = (key: string) => c.plugins.includes(key);
  const L: string[] = [];
  const w = (s = "") => L.push(s);

  w("# Gemfile (development/test group) — deterministic linting toolchain");
  w(`# Generated by Stack Governance Studio · Ruby ${c.rubyVersion}${has("rubocop-rails") ? ` / Rails ${c.railsVersion}` : ""}`);
  w("# Install with: bundle install");
  w("");
  w("group :development, :test do");
  w("  # --- Core static analysis ---------------------------------------------------");
  w("  gem 'rubocop', require: false");
  w("");

  const framework: string[] = [];
  if (has("rubocop-performance")) framework.push("  gem 'rubocop-performance', require: false  # faster / leaner Ruby idioms");
  if (has("rubocop-rails")) framework.push("  gem 'rubocop-rails', require: false         # Rails style guide");
  if (framework.length > 0) {
    w("  # --- Framework & performance extensions -------------------------------------");
    framework.forEach((line) => w(line));
    w("");
  }

  const testing: string[] = [];
  if (has("rubocop-rspec")) testing.push("  gem 'rubocop-rspec', require: false");
  if (has("rubocop-rspec_rails")) testing.push("  gem 'rubocop-rspec_rails', require: false");
  if (has("rubocop-factory_bot")) testing.push("  gem 'rubocop-factory_bot', require: false");
  if (has("rubocop-capybara")) testing.push("  gem 'rubocop-capybara', require: false");
  if (testing.length > 0) {
    w("  # --- Testing ecosystem --------------------------------------------------------");
    testing.forEach((line) => w(line));
    w("");
  }

  if (has("rubocop-rake")) {
    w("  # --- Tooling ---------------------------------------------------------------------");
    w("  gem 'rubocop-rake', require: false");
    w("");
  }

  if (c.ciSecurity) {
    w("  # --- Required by the CI security job --------------------------------------------");
    w("  gem 'brakeman', require: false          # static security scan (OWASP Top 10)");
    w("  gem 'bundler-audit', require: false     # CVE scanner for Gemfile.lock");
    w("");
  }

  const optional = OPTIONAL_PLUGINS.filter((p) => !c.plugins.includes(p));
  if (optional.length > 0) {
    w("  # --- Optional — enable if applicable to your stack -------------------------------");
    optional.forEach((p) => w(`  # gem '${p}', require: false`));
    w("");
  }

  w("end");
  return L.join("\n") + "\n";
}

function generateCiWorkflow(c: BuilderConfig): string {
  const rails = c.plugins.includes("rubocop-rails");
  const L: string[] = [];
  const w = (s = "") => L.push(s);

  w("# .github/workflows/lint.yml");
  w("# Deterministic quality gates — generated by Stack Governance Studio");
  w(`# Target: Ruby ${c.rubyVersion}${rails ? ` / Rails ${c.railsVersion}` : ""}`);
  w("");
  w("name: Lint");
  w("");
  w("on:");
  w("  push:");
  w("    branches: [main]");
  w("  pull_request:");
  w("");
  w("jobs:");
  w("  rubocop:");
  w("    name: RuboCop — style-guide gate");
  w("    runs-on: ubuntu-latest");
  w("    steps:");
  w("      - uses: actions/checkout@v4");
  w("        with:");
  w("          fetch-depth: 0");
  w("      - uses: ruby/setup-ruby@v1");
  w("        with:");
  w(`          ruby-version: "${c.rubyVersion}"`);
  w("          bundler-cache: true");
  w("      # Deterministic gate — never auto-correct (-a / -A) in CI.");
  w("      # Correction is a local, reviewed act: bin/lint.");
  w("      - name: RuboCop");
  w("        run: bundle exec rubocop --format github");

  if (c.ciSecurity) {
    w("");
    w("  security:");
    w("    name: Security — Brakeman · bundler-audit");
    w("    runs-on: ubuntu-latest");
    w("    steps:");
    w("      - uses: actions/checkout@v4");
    w("      - uses: ruby/setup-ruby@v1");
    w("        with:");
    w(`          ruby-version: "${c.rubyVersion}"`);
    w("          bundler-cache: true");
    w("      - name: Brakeman (static security scan — OWASP Top 10)");
    w("        run: bundle exec brakeman -q -z");
    w("      - name: bundler-audit (known CVEs in dependencies)");
    w("        run: bundle exec bundle-audit check --update");
  }

  if (c.specsFirstGate) {
    w("");
    w("  specs-first:");
    w("    name: Specs-First — no app changes without specs");
    w("    runs-on: ubuntu-latest");
    w("    if: github.event_name == 'pull_request'");
    w("    steps:");
    w("      - uses: actions/checkout@v4");
    w("        with:");
    w("          fetch-depth: 0");
    w("      - name: Block app/lib changes without spec changes");
    w("        run: |");
    w('          APP_CHANGES=$(git diff --name-only origin/${{ github.base_ref }} -- app/ lib/)');
    w('          SPEC_CHANGES=$(git diff --name-only origin/${{ github.base_ref }} -- spec/)');
    w('          if [ -n "$APP_CHANGES" ] && [ -z "$SPEC_CHANGES" ]; then');
    w('            echo "::error::Application code changed without updating specs (Specs-First approach)."');
    w("            exit 1");
    w("          fi");
  }

  return L.join("\n") + "\n";
}

function generateLintScript(): string {
  const L: string[] = [
    "#!/usr/bin/env bash",
    "# bin/lint — standardized local quality gate",
    "# Generated by Stack Governance Studio.",
    "# chmod +x bin/lint after creating this file.",
    "",
    "set -euo pipefail",
    "",
    'echo "==> Auto-correcting offenses (safe + unsafe suggestions)..."',
    "bundle exec rubocop -A",
    "",
    'echo "==> Verifying remaining offenses (must be zero)..."',
    "bundle exec rubocop",
  ];
  return L.join("\n") + "\n";
}

function generateSetup(c: BuilderConfig): string {
  const L: string[] = [
    "# Setup — from zero to enforced",
    "# Generated by Stack Governance Studio",
    "",
    "# 1 · Install the toolchain",
    "bundle install",
    "",
    "# 2 · First audit — see the full offense landscape",
    "bundle exec rubocop",
    "",
    "# 3 · Legacy codebase? Freeze existing violations into a baseline",
    "bundle exec rubocop --auto-gen-config",
  ];
  if (c.legacyTodo) {
    L.push("#    → .rubocop_todo.yml (inherit_from is already wired in .rubocop.yml)");
  } else {
    L.push("#    → .rubocop_todo.yml — then wire it: inherit_from: .rubocop_todo.yml");
  }
  L.push(
    "git add .rubocop_todo.yml",
    "",
    "# 4 · Local loop — auto-correct, then hard gate",
    "bin/lint",
    "",
    "# 5 · CI gate — zero tolerance, never auto-correct in CI",
    "bundle exec rubocop --format github",
    "",
    "# 6 · Interrogate a single cop against this config",
    "bundle exec rubocop --show-cops RSpec/ContextWording",
  );
  return L.join("\n") + "\n";
}
